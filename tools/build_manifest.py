#!/usr/bin/env python3
"""Assemble the local release candidate into dist/release/ (no publishing).

Inputs (must already be built):
  dist/*.whl, dist/*.tar.gz          Python package artifacts
  dist/runtime/sap-adt-<ver>-*       per-platform runtime archives
  dist/skills/ dist/plugin/          generated by build_skills / build_plugin

Outputs:
  dist/release/<wheel|sdist|runtime|npm tarball|plugin zip|skill zips>
  dist/release/SHA256SUMS
  dist/release/release-manifest.json   (incl. marketplace candidate entry)

The marketplace entry is a CANDIDATE (state=candidate-not-published): the
live `.claude-plugin/marketplace.json` is never modified here. A human runs
the authorized release step, then swaps in the archive source with the real
URL + digest.

Usage: python tools/build_manifest.py [--skip-npm-pack]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import zipfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO_URL = "https://github.com/shrek-abaper/sap-engineering-skill"


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def version_from_pyproject() -> str:
    for line in (ROOT / "pyproject.toml").read_text(encoding="utf-8").splitlines():
        if line.strip().startswith("version ="):
            return line.split("=", 1)[1].strip().strip('"')
    raise SystemExit("[build_manifest] no version in pyproject.toml")


def zip_dir(src: Path, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(src.rglob("*")):
            if path.is_file():
                zf.write(path, path.relative_to(src))


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True,
                          text=True, check=True).stdout.strip()


def add_artifact(entries: list, path: Path, kind: str, target: str | None = None) -> dict:
    entry = {
        "file": path.name,
        "kind": kind,
        "sha256": sha256(path),
        "size_bytes": path.stat().st_size,
    }
    if target:
        entry["target"] = target
    entries.append(entry)
    return entry


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--skip-npm-pack", action="store_true",
                        help="reuse an existing npm tarball in dist/release/")
    parser.add_argument("--release-state", default="candidate-not-published",
                        choices=["candidate-not-published", "published"],
                        help="npm runtime-manifest state; use 'published' only "
                             "after the GitHub Release exists")
    args = parser.parse_args()

    rel = ROOT / "dist" / "release"
    rel.mkdir(parents=True, exist_ok=True)

    cli_version = version_from_pyproject()
    compat = json.loads((ROOT / "compatibility.json").read_text(encoding="utf-8"))
    plugin_version = compat["plugin_version"]

    artifacts: list[dict] = []

    # --- Python package + runtime archives ---------------------------------
    wheels = sorted((ROOT / "dist").glob("sap_adt-*.whl"))
    sdists = sorted((ROOT / "dist").glob("sap_adt-*.tar.gz"))
    if not wheels or not sdists:
        print("[build_manifest] run `python -m build` first (wheel/sdist missing)",
              file=sys.stderr)
        return 1
    for src in [wheels[-1], sdists[-1]]:
        shutil.copy2(src, rel / src.name)
        add_artifact(artifacts, rel / src.name,
                     "wheel" if src.suffix == ".whl" else "sdist")

    runtime_archives = sorted((ROOT / "dist" / "runtime").glob(f"sap-adt-{cli_version}-*"))
    if not runtime_archives:
        print("[build_manifest] run tools/build_runtime.py first", file=sys.stderr)
        return 1
    for src in runtime_archives:
        target = src.name[len(f"sap-adt-{cli_version}-"):]
        target = target[:-7] if target.endswith(".tar.gz") else target[:-4]
        shutil.copy2(src, rel / src.name)
        add_artifact(artifacts, rel / src.name, "runtime", target)

    # --- npm tarball (regenerated with release URLs, still unpublished) ----
    subprocess.run([sys.executable, str(ROOT / "tools" / "build_npm.py"),
                    "--release-state", args.release_state],
                   cwd=ROOT, check=True)
    if not args.skip_npm_pack:
        packed = subprocess.run(
            ["npm", "pack", "--pack-destination", str(rel)],
            cwd=ROOT / "dist" / "npm", capture_output=True, text=True, check=True,
        ).stdout.strip().splitlines()[-1]
        npm_tarball = rel / Path(packed).name
    else:
        npm_tarball = next(iter(sorted(rel.glob("shrek-abaper-sap-engineering-cli-*.tgz"))), None)
    if npm_tarball is None or not npm_tarball.is_file():
        print("[build_manifest] npm tarball missing", file=sys.stderr)
        return 1
    add_artifact(artifacts, npm_tarball, "npm")

    # --- plugin + skill zips ----------------------------------------------
    plugin_dir = ROOT / "dist" / "plugin"
    if not (plugin_dir / ".claude-plugin" / "plugin.json").is_file():
        subprocess.run([sys.executable, str(ROOT / "tools" / "build_plugin.py")],
                       cwd=ROOT, check=True)
    plugin_zip = rel / f"sap-engineering-skills-{plugin_version}.zip"
    zip_dir(plugin_dir, plugin_zip)
    add_artifact(artifacts, plugin_zip, "plugin")

    skills_root = ROOT / "dist" / "skills"
    for skill_dir in sorted(p for p in skills_root.iterdir() if p.is_dir()):
        skill_zip = rel / f"{skill_dir.name}-{plugin_version}.zip"
        zip_dir(skill_dir, skill_zip)
        add_artifact(artifacts, skill_zip, "skill", skill_dir.name)

    # --- SHA256SUMS + manifest --------------------------------------------
    sums = "".join(f"{a['sha256']}  {a['file']}\n" for a in artifacts)
    (rel / "SHA256SUMS").write_text(sums, encoding="utf-8")

    status = git("status", "--porcelain")
    manifest = {
        "schema_version": 1,
        "cli_version": cli_version,
        "plugin_version": plugin_version,
        "build": {
            "source_commit": git("rev-parse", "HEAD"),
            "dirty_working_tree": bool(status),
            "built_at": datetime.now(timezone.utc).isoformat(),
            "tag": f"sap-adt-v{cli_version} (not created; requires authorization)",
        },
        "artifacts": artifacts,
        "marketplace_candidate": {
            "state": args.release_state,
            "plugin_version": plugin_version,
            "plugin_zip": plugin_zip.name,
            "plugin_zip_sha256": sha256(plugin_zip),
            "source": {
                "source": "archive",
                "url": f"{REPO_URL}/releases/download/sap-adt-v{cli_version}/{plugin_zip.name}",
                "sha256": sha256(plugin_zip),
            },
            "min_claude_code": "2.1.224",
            "note": ("Candidate only — do not copy into the live marketplace "
                     "until the release exists. The live marketplace.json "
                     "stays on source './' until then."),
        },
        "unverified_targets": [
            name for name, t in json.loads(
                (ROOT / "packaging" / "targets.json").read_text(encoding="utf-8")
            )["targets"].items()
            if t["status"] != "verified-local"
        ],
    }
    (rel / "release-manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"[build_manifest] candidate ready: {rel} "
          f"(CLI {cli_version}, plugin {plugin_version}, {len(artifacts)} artifacts)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
